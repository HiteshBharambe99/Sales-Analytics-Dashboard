"""
Prepare the supermarket sales data for the dashboard.

- cleans the raw CSV
- writes sales.data.js (the data the dashboard reads, as a plain <script> so the
  HTML opens by double-click with no server)
- writes summary CSVs to outputs/
- renders static preview charts to outputs/figures/ for the README

    python src/prepare_data.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "supermarket_sales.csv"
OUT = ROOT / "outputs"
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)

# categorical palette (validated, colourblind-safe) from the data-viz guidance
BLUE, ORANGE, AQUA, YELLOW, MAGENTA, GREEN = (
    "#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300",
)
INK, MUTED, GRID = "#0b0b0b", "#898781", "#e1e0d9"


def load() -> pd.DataFrame:
    df = pd.read_csv(RAW)
    df["Date"] = pd.to_datetime(df["Date"], format="%m/%d/%Y")
    df["hour"] = pd.to_datetime(df["Time"], format="%H:%M").dt.hour
    df["dow"] = df["Date"].dt.day_name()
    df = df.rename(columns={
        "Product line": "product_line",
        "Customer type": "customer_type",
        "Gross income": "gross_income",
        "Customer stratification rating": "rating",
    })
    print(f"{len(df)} transactions, {df['Date'].min():%Y-%m-%d} to {df['Date'].max():%Y-%m-%d}")
    return df


def write_dashboard_data(df: pd.DataFrame) -> None:
    records = [
        {
            "date": d.strftime("%Y-%m-%d"),
            "branch": b, "city": c, "product_line": p,
            "customer_type": ct, "gender": g, "payment": pay,
            "total": round(float(t), 2), "quantity": int(q),
            "gross_income": round(float(gi), 2), "rating": float(r), "hour": int(h),
        }
        for d, b, c, p, ct, g, pay, t, q, gi, r, h in zip(
            df["Date"], df["Branch"], df["City"], df["product_line"],
            df["customer_type"], df["Gender"], df["Payment"], df["Total"],
            df["Quantity"], df["gross_income"], df["rating"], df["hour"],
        )
    ]
    js = ROOT / "sales.data.js"
    with open(js, "w") as f:
        f.write("// Generated by src/prepare_data.py — do not edit by hand.\n")
        f.write("window.SALES = ")
        json.dump(records, f)
        f.write(";\n")
    print(f"Wrote {js.name} ({len(records)} records)")


def write_summaries(df: pd.DataFrame) -> None:
    df.groupby("product_line").agg(
        sales=("Total", "sum"), transactions=("Total", "size"),
        gross_income=("gross_income", "sum"), avg_rating=("rating", "mean"),
    ).round(2).sort_values("sales", ascending=False).to_csv(OUT / "by_product_line.csv")

    df.groupby(["Branch", "City"]).agg(
        sales=("Total", "sum"), transactions=("Total", "size"),
        gross_income=("gross_income", "sum"),
    ).round(2).to_csv(OUT / "by_branch.csv")

    kpis = {
        "total_sales": round(float(df["Total"].sum()), 2),
        "transactions": int(len(df)),
        "avg_transaction": round(float(df["Total"].mean()), 2),
        "gross_income": round(float(df["gross_income"].sum()), 2),
        "avg_rating": round(float(df["rating"].mean()), 2),
        "units_sold": int(df["Quantity"].sum()),
    }
    with open(OUT / "kpis.json", "w") as f:
        json.dump(kpis, f, indent=2)
    print("KPIs:", kpis)


def previews(df: pd.DataFrame) -> None:
    plt.rcParams.update({"axes.edgecolor": GRID, "axes.labelcolor": INK,
                         "text.color": INK, "xtick.color": MUTED, "ytick.color": MUTED})

    # sales by product line
    s = df.groupby("product_line")["Total"].sum().sort_values()
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.barh(s.index, s.values, color=BLUE)
    ax.set_title("Sales by product line", color=INK, fontweight="bold")
    ax.set_xlabel("Sales ($)")
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    fig.tight_layout(); fig.savefig(FIG / "sales_by_product_line.png", dpi=120); plt.close(fig)

    # daily sales trend
    daily = df.groupby("Date")["Total"].sum()
    fig, ax = plt.subplots(figsize=(10, 4))
    ax.plot(daily.index, daily.values, color=BLUE, linewidth=2)
    ax.set_title("Daily sales", color=INK, fontweight="bold")
    ax.set_ylabel("Sales ($)")
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    fig.tight_layout(); fig.savefig(FIG / "daily_sales.png", dpi=120); plt.close(fig)

    # sales by branch + payment (grouped)
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    b = df.groupby("City")["Total"].sum().sort_values(ascending=False)
    axes[0].bar(b.index, b.values, color=[BLUE, ORANGE, AQUA])
    axes[0].set_title("Sales by city", color=INK, fontweight="bold")
    axes[0].set_ylabel("Sales ($)")
    p = df.groupby("Payment")["Total"].sum().sort_values(ascending=False)
    axes[1].bar(p.index, p.values, color=[BLUE, ORANGE, AQUA])
    axes[1].set_title("Sales by payment method", color=INK, fontweight="bold")
    for ax in axes:
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    fig.tight_layout(); fig.savefig(FIG / "city_and_payment.png", dpi=120); plt.close(fig)
    print("Saved preview figures")


def main() -> None:
    df = load()
    write_dashboard_data(df)
    write_summaries(df)
    previews(df)


if __name__ == "__main__":
    main()
